void OLED_Init(sOLEDHandle *hOLED) {
    oled = *hOLED;
    for (int i = 0; i < sizeof(init_cmds); i++) {
        oled.I2C_WriteCmd(init_cmds[i]);
    }
    OLED_Clear();

    // --- LÍNEA DE PRUEBA DE FUEGO ---
        // Dibujamos un texto gigante en la memoria antes de mandar el Update
        OLED_Print(10, 20, "TEST OK", 2, 1);
    OLED_Update();
}

void OLED_Update(void) {
    if (oled_status == OLED_IDLE) {
        oled_status = OLED_BUSY;
        pagina_actual = 0;
        sub_estado = 0; // Nos aseguramos de arrancar limpios
    }
}

void OLED_Task(void) {
    // Si no hay nada que actualizar, salimos
    if (oled_status != OLED_BUSY) return;

    // Si ya mandamos las 8 páginas (0 a 7), terminamos el cuadro
    if (pagina_actual > 7) {
        oled_status = OLED_IDLE;
        return;
    }

    if (sub_estado == 0) {
        oled.I2C_WriteCmd(0xB0 + pagina_actual);
        oled.I2C_WriteCmd(0x02); // Dejamos el offset de 0x02 por si es de 1.3"
        oled.I2C_WriteCmd(0x10);
        sub_estado = 1;
    }
    else if (sub_estado == 1) {
        uint8_t *ptr_datos = &bufferRAM[pagina_actual * 128];
        oled.I2C_WriteData_DMA(ptr_datos, 128);
        sub_estado = 2; // El microcontrolador se queda esperando en estado 2
    }
}

void OLED_DMA_Callback(void) {
    if (oled_status == OLED_BUSY) {
        pagina_actual++; // Avanzamos a la fila de abajo
        sub_estado = 0;  // ¡LA MAGIA! Volvemos a cero para destrabar la Task
    }
}

