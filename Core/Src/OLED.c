void OLED_ShowTelemetry(uint16_t ir_izq, uint16_t ir_cen, uint16_t ir_der) {
    char buf[30];

    // 1. Limpiamos el buffer local
    OLED_Clear();

    // 2. Encabezado en tamaño 2 con subrayado
    OLED_Print(0, 0, "TELEMETRIA", 2, 1);
    OLED_DrawHLine(0, 16, 128, 1);

    // 3. Imprimimos los valores formateados
    sprintf(buf, "IR Izq: %4u", ir_izq);
    OLED_Print(0, 22, buf, 1, 1);

    sprintf(buf, "IR Cen: %4u", ir_cen);
    OLED_Print(0, 34, buf, 1, 1);

    sprintf(buf, "IR Der: %4u", ir_der);
    OLED_Print(0, 46, buf, 1, 1);

    // 4. Marcamos el buffer como listo para ser enviado por la Task
    OLED_Update();
}
