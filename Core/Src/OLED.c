void OLED_Clear(void) {
    memset(bufferRAM, 0x00, sizeof(bufferRAM));
}

void OLED_DrawPixel(uint8_t x, uint8_t y, uint8_t color) {
    if (x >= 128 || y >= 64) return;
    uint16_t indice = x + ((y / 8) * 128);

    if (color) {
        bufferRAM[indice] |= (1 << (y % 8));
    } else {
        bufferRAM[indice] &= ~(1 << (y % 8));
    }
}

void OLED_DrawHLine(uint8_t x, uint8_t y, uint8_t length, uint8_t color) {
    for (uint8_t i = 0; i < length; i++) {
        OLED_DrawPixel(x + i, y, color);
    }
}
void OLED_DrawVLine(uint8_t x, uint8_t y, uint8_t length, uint8_t color) {
    for (uint8_t i = 0; i < length; i++) {
        OLED_DrawPixel(x, y + i, color);
    }
}

void OLED_DrawRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t color) {
    OLED_DrawHLine(x, y, w, color);
    OLED_DrawHLine(x, y + h - 1, w, color);
    OLED_DrawVLine(x, y, h, color);
    OLED_DrawVLine(x + w - 1, y, h, color);
}

void OLED_FillRect(uint8_t x, uint8_t y, uint8_t w, uint8_t h, uint8_t color) {
    for (uint8_t i = 0; i < h; i++) {
        OLED_DrawHLine(x, y + i, w, color);
    }
}

void OLED_DrawCircle(int32_t x0, int32_t y0, int32_t radius, uint8_t color) {
    int32_t x = radius;
    int32_t y = 0;
    int32_t err = 0;

    while (x >= y) {
        // Aprovechamos la simetría de 8 octantes del círculo
        OLED_DrawPixel(x0 + x, y0 + y, color);
        OLED_DrawPixel(x0 + y, y0 + x, color);
        OLED_DrawPixel(x0 - y, y0 + x, color);
        OLED_DrawPixel(x0 - x, y0 + y, color);
        OLED_DrawPixel(x0 - x, y0 - y, color);
        OLED_DrawPixel(x0 - y, y0 - x, color);
        OLED_DrawPixel(x0 + y, y0 - x, color);
        OLED_DrawPixel(x0 + x, y0 - y, color);

        if (err <= 0) {
            y += 1;
            err += 2 * y + 1;
        }

        if (err > 0) {
            x -= 1;
            err -= 2 * x + 1;
        }
    }
}

void OLED_PutChar(uint8_t x, uint8_t y, char c, uint8_t size, uint8_t color) {
    if (c < 32 || c > 126) return;

    for (uint8_t i = 0; i < 5; i++) {
        uint8_t linea_bits = font5x7[(c - 32) * 5 + i];

        for (uint8_t j = 0; j < 8; j++) {
            if (linea_bits & (1 << j)) {
                if (size == 1) {
                    OLED_DrawPixel(x + i, y + j, color);
                } else {
                    for (uint8_t sx = 0; sx < size; sx++) {
                        for (uint8_t sy = 0; sy < size; sy++) {
                            OLED_DrawPixel(x + (i * size) + sx, y + (j * size) + sy, color);
                        }
                    }
                }
            }
        }
    }
}

void OLED_Print(uint8_t x, uint8_t y, const char* str, uint8_t size, uint8_t color) {
    uint8_t cursor_x = x;
    while (*str) {
        OLED_PutChar(cursor_x, y, *str, size, color);
        cursor_x += (5 * size) + 1;
        str++;
    }
}

